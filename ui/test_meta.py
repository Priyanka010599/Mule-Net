@pytest.mark.parametrize("path", ["/api/metrics", "/api/coalition", "/api/redteam", "/api/enclave"])
def test_artifact_endpoints_send_etag_and_answer_304(env: Path, path: str) -> None:
    with TestClient(app) as client:
        first = client.get(path)
        assert first.status_code == 200
        etag = first.headers["etag"]
        assert "max-age=" in first.headers["cache-control"]
        again = client.get(path, headers={"If-None-Match": etag})
        assert again.status_code == 304
        assert again.content == b""
        assert again.headers["etag"] == etag
        other = client.get(path, headers={"If-None-Match": '"nope"'})
        assert other.status_code == 200


def test_etag_changes_when_the_artifact_content_changes(env: Path) -> None:
    with TestClient(app) as client:
        before = client.get("/api/redteam").headers["etag"]
        doc = json.loads((env / "redteam_fb.json").read_text(encoding="utf-8"))
        doc["generated_at"] = "2026-10-08T00:00:00+00:00"
        (env / "redteam_fb.json").write_text(json.dumps(doc), encoding="utf-8")
        after = client.get("/api/redteam", headers={"If-None-Match": before})
    assert after.status_code == 200
    assert after.headers["etag"] != before
