#: The real content of each bundled fallback (full shape, so /api/metrics etc.
#: still render correctly) with ONLY ``generated_at`` pinned to a fixed value.
#: Not a straight copy: the real files are regenerated by
#: `python -m ui.build_snapshot`, and their ``generated_at`` moves forward
#: every time that happens -- which previously made this staleness test's
#: pass/fail depend on whether someone had recently refreshed real data
#: (observed live: it broke exactly that way once metrics and lead_time were
#: regenerated and genuinely stopped being stale). Pinning only the one field
#: the staleness assertions care about keeps everything else real.
_FIXED_GENERATED_AT: dict[str, str] = {
    "metrics": "2026-09-26T14:27:46+00:00",
    "lead_time": "2026-09-26T14:48:55+00:00",
    "coalition": "2026-10-04T14:20:38+00:00",
    "redteam": "2026-09-28T03:09:08+00:00",
}


def _pinned_fallback(name: str) -> dict:
    from ui.config import DEFAULT_UI_DATA_DIR

    doc = json.loads((DEFAULT_UI_DATA_DIR / f"{name}_fallback.json").read_text(encoding="utf-8"))
    doc["generated_at"] = _FIXED_GENERATED_AT[name]
    return doc


@pytest.fixture
def env(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> Path:
    """An isolated artifact set: real fallback content, pinned generation times."""
    ml_out = tmp_path / "ml_out"
    ml_out.mkdir()
    (ml_out / "manifest.json").write_text(json.dumps(_MANIFEST), encoding="utf-8")
    (tmp_path / "snap.json").write_text(json.dumps(_SNAPSHOT), encoding="utf-8")
    for name in ("metrics", "lead_time", "coalition", "redteam"):
        (tmp_path / f"{name}_fb.json").write_text(
            json.dumps(_pinned_fallback(name)), encoding="utf-8"
        )
        monkeypatch.setenv(
            {
                "metrics": "MULENET_UI_METRICS_FALLBACK",
                "lead_time": "MULENET_UI_LEAD_METRICS_FALLBACK",
                "coalition": "MULENET_UI_COALITION_FALLBACK",
                "redteam": "MULENET_UI_REDTEAM_FALLBACK",
            }[name],
            str(tmp_path / f"{name}_fb.json"),
        )
        # Live paths point at nothing, as in the deployed container.
        monkeypatch.setenv(
            {
                "metrics": "MULENET_UI_METRICS",
                "lead_time": "MULENET_UI_LEAD_METRICS",
                "coalition": "MULENET_UI_COALITION",
                "redteam": "MULENET_UI_REDTEAM",
            }[name],
            str(tmp_path / "absent.json"),
        )
    monkeypatch.setenv("MULENET_UI_SNAPSHOT", str(tmp_path / "snap.json"))
    monkeypatch.setenv("MULENET_UI_ML_OUT", str(ml_out))
    return tmp_path


def _meta(env: Path) -> dict:
    with TestClient(app) as client:
        return client.get("/api/meta").json()


def _by_name(meta: dict) -> dict[str, dict]:
    return {a["name"]: a for a in meta["artifacts"]}


def test_meta_lists_every_artifact_with_hash_seed_source_and_versions(env: Path) -> None:
    meta = _meta(env)
    arts = _by_name(meta)
    assert set(arts) == {
        "snapshot", "ml_manifest", "metrics", "lead_time", "coalition", "redteam", "enclave"
    }
    redteam = arts["redteam"]
    expected = hashlib.sha256((env / "redteam_fb.json").read_bytes()).hexdigest()[:12]
    assert redteam["data_version"] == expected
    assert redteam["source"] == "bundled fallback"
    assert redteam["generated_at"].startswith("2026-09-28")
    assert arts["ml_manifest"]["seed"] == ["42"]
    assert arts["snapshot"]["seed"] == ["42"]
    assert "42" in arts["metrics"]["seed"] and "42" in arts["lead_time"]["seed"]
    assert arts["enclave"]["source"] == "bundled"
    # versions are read from the artifacts, not hardcoded
    assert meta["versions"] == {
        "detector_version": "rule-vX",
        "score_model_version": "model-vY",
        "explainer_version": "expl-vZ",
    }


def test_artifacts_older_than_the_ml_run_are_flagged_stale_with_a_reason(env: Path) -> None:
    arts = _by_name(_meta(env))
    # Real fallbacks: metrics/lead_time 2026-09-26 and redteam 2026-09-28T03 predate the
    # synthetic 2026-09-28T07 manifest; coalition (10-04), snapshot and enclave do not.
    for name in ("metrics", "lead_time", "redteam"):
        assert arts[name]["stale"] is True, name
        assert "before the ml/out run" in arts[name]["stale_reason"]
    assert "thresholds" in arts["redteam"]["stale_reason"]
    assert "ml.early" in arts["metrics"]["stale_reason"]
    for name in ("coalition", "snapshot", "enclave", "ml_manifest"):
        assert arts[name]["stale"] is False, name
        assert arts[name]["stale_reason"] is None


def test_staleness_survives_without_ml_out_via_snapshot_data_basis(env: Path) -> None:
    (env / "ml_out" / "manifest.json").unlink()
    snap = {**_SNAPSHOT, "data_basis": {"ml_manifest_generated_at": _MANIFEST["generated_at"]}}
    (env / "snap.json").write_text(json.dumps(snap), encoding="utf-8")
    meta = _meta(env)
    assert _by_name(meta)["metrics"]["stale"] is True
    assert meta["data_reference"]["from"] == "snapshot data_basis"


def test_no_reference_means_not_stale_rather_than_guessing(env: Path) -> None:
    (env / "ml_out" / "manifest.json").unlink()
    assert not any(a["stale"] for a in _meta(env)["artifacts"])


def test_consistency_check_warns_on_disagreement_without_raw_ids(
    env: Path, caplog: pytest.LogCaptureFixture
) -> None:
    bad = {**_SNAPSHOT, "source": "x seed 7", "detector": {"detector_version": "rule-vOLD"}}
    (env / "snap.json").write_text(json.dumps(bad), encoding="utf-8")
    with caplog.at_level(logging.WARNING, logger="mulenet.ui.provenance"):
        with TestClient(app):
            pass
    text = "\n".join(r.getMessage() for r in caplog.records)
    assert "seed disagrees" in text
    assert "rule version disagrees" in text
    assert "detected ring count disagrees" not in text  # snapshot.dataset 45 == manifest 45
    assert all(r.levelno == logging.WARNING for r in caplog.records)


