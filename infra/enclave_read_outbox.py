#!/usr/bin/env python3
"""Download and decrypt one bank's outbox alerts. Run at the bank, not the operator.

This is the receiving half of per-bank outbox encryption: the enclave seals
each bank's alert bundle to that bank's own public key
(``enclave/outbox_crypto.py``), and only this script, holding the matching
private key generated by ``infra/enclave_outbox_keygen.py``, can open it. The
operator can run this same download against the same bucket and get back
nothing but ciphertext -- that is the property this script exists to
demonstrate, not just to use.

Usage:

    python -m infra.enclave_read_outbox \\
        --bank-id bank-a --run-id stage3 \\
        --outbox-bucket mulenet-enclave-outbox \\
        --project mulenet
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
if str(REPO_ROOT) not in sys.path:
    sys.path.insert(0, str(REPO_ROOT))

from enclave.outbox_crypto import SealedOutbox, unseal_with_private_key  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    from google.cloud import storage

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--bank-id", required=True)
    parser.add_argument("--run-id", required=True)
    parser.add_argument("--outbox-bucket", required=True)
    parser.add_argument("--project", required=True, help="Operator project that owns the bucket.")
    parser.add_argument(
        "--private-key-file",
        default=None,
        help="Defaults to .enclave-outbox-key-<bank-id>.bin in the repo root.",
    )
    args = parser.parse_args(argv)

    key_path = Path(args.private_key_file) if args.private_key_file else (
        REPO_ROOT / f".enclave-outbox-key-{args.bank_id}.bin"
    )
    if not key_path.exists():
        print(f"private key not found at {key_path}. Run infra.enclave_outbox_keygen first.", file=sys.stderr)
        return 1
    private_key = key_path.read_bytes()

    client = storage.Client(project=args.project)
    prefix = f"outbox/{args.bank_id}/{args.run_id}/"
    blobs = list(client.list_blobs(args.outbox_bucket, prefix=prefix))
    if not blobs:
        print(f"no outbox objects found under gs://{args.outbox_bucket}/{prefix}", file=sys.stderr)
        return 1

    for blob in blobs:
        raw = blob.download_as_text()
        sealed = SealedOutbox.from_json(raw)
        plaintext = unseal_with_private_key(sealed, private_key)
        print(f"=== {blob.name} ===")
        print(plaintext.decode())
        print()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
